void fb_draw_char(int x, int y, char c, u32 color){
    if(c<32||c>126) return;
    const u8* glyph = font8x14[(u8)(c-32)];
    for(int row=0;row<14;row++){
        u8 bits=glyph[row];
        for(int col=0;col<8;col++)
            if(bits&(0x80>>col)) fb_pixel(x+col, y+row, color);
    }
}
void fb_draw_text(int x, int y, const char* s, u32 color){
    int cx=x;
    for(;*s;s++){
        if(*s=='\n'){ cx=x; y+=15; continue; }
        fb_draw_char(cx,y,*s,color);
        cx+=8;
    }
}
void fb_line(int x0,int y0,int x1,int y1,u32 c){
    int dx=x1-x0; if(dx<0)dx=-dx;
    int dy=y1-y0; if(dy<0)dy=-dy;
    int sx=x0<x1?1:-1, sy=y0<y1?1:-1, err=dx-dy;
    for(;;){
        fb_pixel(x0,y0,c);
        if(x0==x1&&y0==y1) break;
        int e2=err*2;
        if(e2>-dy){err-=dy;x0+=sx;}
        if(e2< dx){err+=dx;y0+=sy;}
    }
}
void fb_circle(int cx,int cy,int r,u32 c){
    int x=0,y=r,d=3-2*r;
    while(y>=x){
        fb_pixel(cx+x,cy+y,c); fb_pixel(cx-x,cy+y,c);
        fb_pixel(cx+x,cy-y,c); fb_pixel(cx-x,cy-y,c);
        fb_pixel(cx+y,cy+x,c); fb_pixel(cx-y,cy+x,c);
        fb_pixel(cx+y,cy-x,c); fb_pixel(cx-y,cy-x,c);
        if(d<0) d+=4*x+6; else{d+=4*(x-y)+10;y--;}
        x++;
    }
}
